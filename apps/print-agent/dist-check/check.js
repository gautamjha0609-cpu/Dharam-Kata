var PT_TO_MM = 25.4 / 72;
var approxMeasure = (text, family, pt, bold) => {
  const em = pt * PT_TO_MM;
  if (FONT_FAMILIES[family].mono) {
    let units2 = 0;
    for (const ch of text) units2 += ch.charCodeAt(0) > 127 ? 0.8 : 0.6;
    return units2 * em;
  }
  let units = 0;
  for (const ch of text) units += ch.charCodeAt(0) > 127 ? 0.75 : /[A-Z0-9]/.test(ch) ? 0.62 : 0.52;
  return units * em * (bold ? 1.08 : 1);
};
var STEP = 0.25;
function wrap(text, maxW, m2, maxLines) {
  const words = text.split(/\s+/).filter(Boolean);
  const lines = [];
  let cur = "";
  for (const w of words) {
    const t = cur ? `${cur} ${w}` : w;
    if (m2(t) <= maxW) cur = t;
    else {
      if (cur) lines.push(cur);
      if (m2(w) > maxW) return null;
      cur = w;
    }
    if (lines.length >= maxLines) return null;
  }
  if (cur) lines.push(cur);
  return lines.length <= maxLines ? lines : null;
}
function fitText(text, f2, floorPt, measure = approxMeasure) {
  const { family, minPt, maxPt, bold } = f2.font;
  const fam = family;
  const clean = text.replace(/\s+/g, " ").trim();
  const fitsHeight = (pt, n) => n * pt * PT_TO_MM * f2.lineHeight <= f2.h + 1e-6;
  for (let pt = maxPt; pt >= minPt - 1e-9; pt -= STEP) {
    const m3 = (s) => measure(s, fam, pt, bold);
    if (f2.fit === "wrap" && f2.maxLines > 1) {
      const lines = wrap(clean, f2.w, m3, f2.maxLines);
      if (lines && fitsHeight(pt, lines.length)) return { pt, lines, overflow: false, belowFloor: pt < floorPt };
    } else if (m3(clean) <= f2.w + 1e-6 && fitsHeight(pt, 1)) {
      return { pt, lines: [clean], overflow: false, belowFloor: pt < floorPt };
    } else if (!fitsHeight(pt, 1)) {
      continue;
    }
  }
  const m2 = (s) => measure(s, fam, minPt, bold);
  let cut = clean;
  while (cut.length > 0 && m2(cut) > f2.w) cut = cut.slice(0, -1);
  return { pt: minPt, lines: [cut], overflow: true, belowFloor: minPt < floorPt };
}

