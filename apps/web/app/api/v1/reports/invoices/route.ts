import ExcelJS from "exceljs";
import { currentUser, fail, rateLimit } from "@/lib/api";
import { serviceClient } from "@/lib/supabase-server";

const MAX_ROWS = 20_000;
const uuid = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i;
const day = /^\d{4}-\d{2}-\d{2}$/;

interface Inv {
  invoice_number: string; issued_at: string; status: string; payment_mode: string; party_name: string | null; vehicle_display: string; material: string | null;
  stage: "open" | "closed"; extra: Record<string, string> | null;
  gross_weight_kg: string; tare_weight_kg: string | null; net_weight_kg: string | null; weight_unit: string; quantity: string; rate: string; fee_total: string; site_id: string;
  gross_weight_at: string; tare_weight_at: string | null; id: string; cancel_reason: string | null; party_id: string | null;
}

const IST = "Asia/Kolkata";
const fmt = (iso: string) => new Intl.DateTimeFormat("en-GB", { timeZone: IST, day: "2-digit", month: "2-digit", year: "numeric", hour: "2-digit", minute: "2-digit", hour12: false }).format(new Date(iso)).replace(",", "");

/**
 * Excel export of invoices for a date range. Uses the CALLER's session (RLS), so a user can only export what they
 * can already see on screen (tenant + site scope). Every export is written to the audit log.
 */
export async function GET(req: Request) {
  const user = await currentUser();
  if (!user) return fail(401, "unauthenticated", "Please sign in.");
  if (!rateLimit(`export:${user.id}`, 10, 60_000)) return fail(429, "rate_limited", "Too many exports. Try again shortly.");
  const q = new URL(req.url).searchParams;
  const org = q.get("organization_id") ?? "";
  const from = q.get("from") ?? "";
  const to = q.get("to") ?? "";
  const mode = q.get("mode") ?? "";
  const site = q.get("site_id") ?? "";
  if (!uuid.test(org) || !day.test(from) || !day.test(to) || (site && !uuid.test(site)) || !["", "cash", "credit"].includes(mode)) return fail(400, "invalid_request", "Choose a valid date range.");
  const { data: allowed } = await user.sb.rpc("has_permission", { org, perm: "report.export" });
  if (!allowed) return fail(403, "forbidden", "You do not have permission to export reports.");

  const start = new Date(`${from}T00:00:00+05:30`);
  const end = new Date(new Date(`${to}T00:00:00+05:30`).getTime() + 86_400_000);
  if (!(start < end) || end.getTime() - start.getTime() > 366 * 86_400_000) return fail(400, "invalid_range", "Date range must be within one year.");

  let qb = user.sb.from("invoices").select("*").eq("organization_id", org).gte("issued_at", start.toISOString()).lt("issued_at", end.toISOString()).order("issued_at").limit(MAX_ROWS + 1);
  if (mode) qb = qb.eq("payment_mode", mode);
  if (site) qb = qb.eq("site_id", site);
  const { data, error } = await qb;
  if (error) return fail(500, "query_failed", "Could not read invoices.");
  const rows = (data ?? []) as unknown as Inv[];
  if (rows.length > MAX_ROWS) return fail(413, "too_large", `More than ${MAX_ROWS} invoices. Narrow the date range.`);

  const ids = rows.map((r) => r.id);
  const bal = new Map<string, { paid: number; out: number }>();
  for (let i = 0; i < ids.length; i += 200) {
    const { data: b } = await user.sb.from("invoice_balances").select("invoice_id,amount_paid,outstanding").in("invoice_id", ids.slice(i, i + 200));
    for (const x of (b ?? []) as { invoice_id: string; amount_paid: string; outstanding: string }[]) bal.set(x.invoice_id, { paid: Number(x.amount_paid), out: Number(x.outstanding) });
  }
  const { data: siteRows } = await user.sb.from("sites").select("id,name").eq("organization_id", org);
  const siteName = new Map(((siteRows ?? []) as { id: string; name: string }[]).map((s) => [s.id, s.name]));
  const { data: orgRow } = await user.sb.from("organizations").select("display_name").eq("id", org).maybeSingle();
  const { data: prof } = await user.sb.from("profiles").select("full_name,login_id").eq("user_id", user.id).maybeSingle();

  const issued = rows.filter((r) => r.status === "issued");
  const sum = (f: (r: Inv) => number, set = issued) => set.reduce((a, r) => a + f(r), 0);
  const cash = issued.filter((r) => r.payment_mode === "cash");
  const credit = issued.filter((r) => r.payment_mode === "credit");

  const wb = new ExcelJS.Workbook();
  wb.creator = "Dharam Kata";
  const s = wb.addWorksheet("Summary");
  s.columns = [{ width: 34 }, { width: 28 }];
  const meta: [string, string | number][] = [
    ["Organisation", (orgRow as { display_name: string } | null)?.display_name ?? ""],
    ["Report", "Invoice register"],
    ["Date range (IST)", `${from} to ${to}`],
    ["Payment filter", mode || "All"],
    ["Site filter", site ? siteName.get(site) ?? site : "All sites"],
    ["Generated by", (prof as { full_name: string } | null)?.full_name || (prof as { login_id: string } | null)?.login_id || ""],
    ["Generated at (IST)", fmt(new Date().toISOString())],
    ["Times shown are", "Weighing event times (IST), not record-creation times"],
    ["", ""],
    ["Invoices issued", issued.length],
    ["Invoices cancelled (excluded from totals)", rows.length - issued.length],
    ["Total net weight (kg, closed entries)", sum((r) => Number(r.net_weight_kg ?? 0))],
    ["Open entries (second weight pending)", issued.filter((r) => r.stage === "open").length],
    ["Total amount (INR) — last amount of each entry", sum((r) => Number(r.fee_total))],
    ["Cash invoices (INR)", sum((r) => Number(r.fee_total), cash)],
    ["Credit invoices (INR)", sum((r) => Number(r.fee_total), credit)],
    ["Collected (INR)", sum((r) => bal.get(r.id)?.paid ?? 0)],
    ["Outstanding (INR)", sum((r) => bal.get(r.id)?.out ?? 0)],
  ];
  meta.forEach((m) => s.addRow(m));
  s.getColumn(1).font = { bold: true };
  for (const r of [12, 13, 14, 15, 16, 17]) s.getRow(r).getCell(2).numFmt = "#,##0.00";

  const { data: xdefs } = await user.sb.from("custom_fields").select("key,label_en").eq("organization_id", org).order("key");
  const xcols = ((xdefs ?? []) as { key: string; label_en: string }[]).filter((c) => rows.some((r) => r.extra?.[c.key]));
  const d = wb.addWorksheet("Invoices", { views: [{ state: "frozen", ySplit: 1 }] });
  d.columns = [
    { header: "Invoice no", key: "no", width: 22 }, { header: "Issued (IST)", key: "at", width: 18 }, { header: "Status", key: "st", width: 11 },
    { header: "Site", key: "site", width: 18 }, { header: "Vehicle", key: "veh", width: 16 }, { header: "Party", key: "party", width: 26 }, { header: "Material", key: "mat", width: 20 },
    { header: "Entry", key: "stg", width: 9 }, { header: "Loaded / first weight (kg)", key: "g", width: 17 }, { header: "Weighed at (IST)", key: "gat", width: 18 }, { header: "Empty (kg)", key: "t", width: 13 }, { header: "Empty at (IST)", key: "tat", width: 18 },
    { header: "Net (kg)", key: "n", width: 13 },
    { header: "Amount (INR) — last entered", key: "f", width: 18 }, { header: "Payment", key: "pm", width: 10 }, { header: "Paid (INR)", key: "p", width: 13 }, { header: "Outstanding (INR)", key: "o", width: 17 }, { header: "Cancel reason", key: "cr", width: 28 },
    ...xcols.map((c) => ({ header: c.label_en, key: c.key, width: 20 })),
  ];
  d.getRow(1).font = { bold: true, color: { argb: "FFFFFFFF" } };
  d.getRow(1).fill = { type: "pattern", pattern: "solid", fgColor: { argb: "FF0B2D4C" } };
  for (const r of rows) {
    const b = bal.get(r.id);
    d.addRow({
      no: r.invoice_number, at: fmt(r.issued_at), st: r.status, site: siteName.get(r.site_id) ?? "", veh: r.vehicle_display, party: r.party_name ?? "Walk-in", mat: r.material ?? "",
      stg: r.stage === "open" ? "Open" : "Closed", g: Number(r.gross_weight_kg), gat: fmt(r.gross_weight_at),
      t: r.tare_weight_kg === null ? "" : Number(r.tare_weight_kg), tat: r.tare_weight_at ? fmt(r.tare_weight_at) : "", n: r.net_weight_kg === null ? "" : Number(r.net_weight_kg),
      f: Number(r.fee_total), pm: r.payment_mode, p: b?.paid ?? 0, o: b?.out ?? 0, cr: r.cancel_reason ?? "",
      ...Object.fromEntries(xcols.map((c) => [c.key, r.extra?.[c.key] ?? ""])),
    });
  }
  for (const k of ["g", "t", "n"]) d.getColumn(k).numFmt = "#,##0.000";
  for (const k of ["f", "p", "o"]) d.getColumn(k).numFmt = "#,##0.00";
  d.autoFilter = { from: "A1", to: { row: 1, column: d.columnCount } };

  const buf = Buffer.from(await wb.xlsx.writeBuffer());
  await serviceClient().rpc("write_audit", { p_org: org, p_site: (site || null) as unknown as string, p_actor: user.id, p_action: "report.export", p_entity_type: "invoice_register", p_entity_id: null as unknown as string, p_reason: null as unknown as string, p_meta: { from, to, mode, rows: rows.length } });
  return new Response(buf, {
    headers: {
      "content-type": "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet",
      "content-disposition": `attachment; filename="invoices_${from}_to_${to}.xlsx"`,
      "cache-control": "private, no-store",
    },
  });
}
